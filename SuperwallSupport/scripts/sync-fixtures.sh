#!/usr/bin/env bash
# Copies the superwall-support/1 wire fixtures and JSON Schema from paywall-next
# into the test bundle, and records the exact source commit.
#
#   SuperwallSupport/scripts/sync-fixtures.sh /path/to/paywall-next [ref]
#
# `ref` defaults to origin/main. The files come from that commit (git archive),
# never from the checkout's working tree, so SOURCE.json is always true.
set -euo pipefail

repo="${1:?usage: sync-fixtures.sh /path/to/paywall-next [ref]}"
ref="${2:-origin/main}"
here="$(cd "$(dirname "$0")/.." && pwd)"
dest="$here/Tests/SuperwallSupportTests/Fixtures"

sha="$(git -C "$repo" rev-parse "$ref^{commit}")"
tmp="$(mktemp -d)"
trap 'rm -rf "$tmp"' EXIT

git -C "$repo" archive "$sha" packages/inbox-contracts/fixtures packages/inbox-contracts/json-schema \
  | tar -x -C "$tmp"

rm -rf "$dest"
mkdir -p "$dest"
cp -R "$tmp/packages/inbox-contracts/fixtures/." "$dest/"
mkdir -p "$dest/json-schema"
cp -R "$tmp/packages/inbox-contracts/json-schema/." "$dest/json-schema/"

cat > "$dest/SOURCE.json" <<JSON
{
  "repository": "superwall/paywall-next",
  "commit": "$sha",
  "ref": "$ref",
  "paths": ["packages/inbox-contracts/fixtures", "packages/inbox-contracts/json-schema"],
  "note": "Generated by SuperwallSupport/scripts/sync-fixtures.sh. Do not edit; re-run the script."
}
JSON

echo "Synced fixtures from $sha ($ref) into $dest"
